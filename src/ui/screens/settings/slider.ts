/**
 * Арифметика ползунка «протяните, чтобы удалить» из опасной зоны (FR-7.4).
 *
 * Сам жест живёт в `PanResponder`, а расчёты вынесены сюда: чистые функции
 * проверяются тестами на границах, чего с жестом в jest не сделать.
 */

/**
 * Доля пройденного пути, 0…1. `width` — длина хода ручки (ширина дорожки за
 * вычетом самой ручки), поэтому у правого края получается ровно единица.
 */
export const sliderProgress = (dx: number, width: number): number => {
  if (!(width > 0)) return 0
  if (!(dx > 0)) return 0
  return Math.min(1, dx / width)
}

/** Ползунок дотянут только у самого края: на полпути отпускать бесполезно. */
export const isSlideComplete = (progress: number): boolean => progress >= 1
